local utils = require 'mp.utils'
local dir = utils.join_path(mp.get_opt('animpv-test-root'), 'history')
test('history survives restart and preserves a useful position at EOF', function()
    local H = module('history')
    local a = H.new(dir, 3)
    assert(a:save('C:/Медиа/01.mkv', {position=65, duration=100, audio='studio'}))
    assert(a:save('C:/Медиа/01.mkv', {position=100, duration=100}))
    local b = H.new(dir, 3)
    equal(b:get('C:/Медиа/01.mkv').position, 65)
    equal(b:get('C:/Медиа/01.mkv').audio, 'studio')
end)
test('concurrent history writers merge instead of dropping unrelated media', function()
    local H = module('history')
    local a, b = H.new(dir, 3), H.new(dir, 3)
    a:save('one.mkv', {position=11, duration=100})
    b:save('two.mkv', {position=22, duration=100})
    equal(H.new(dir, 3):get('one.mkv').position, 11)
    equal(H.new(dir, 3):get('two.mkv').position, 22)
end)
test('history ignores malformed and truncated records and enforces display cap', function()
    local H = module('history')
    local path = utils.join_path(dir, 'history-0000000000-999-000001.jsonl')
    local f = assert(io.open(path, 'wb'))
    f:write('bad\n{"path":2}\n{"version":1,"path":"valid.mkv","position":13,"updated":1}\n{"path":"incomplete')
    f:close()
    equal(H.new(dir,20):get('valid.mkv').position,13)
    local a = H.new(dir, 2)
    a:save('three.mkv', {position=33, duration=100})
    a:save('four.mkv', {position=44, duration=100})
    equal(#H.new(dir, 2):list(), 2)
end)
test('history rejects nonfinite negative or oversized records', function()
    local a = module('history').new(dir, 3)
    equal(a:save('bad.mkv', {position=-3}), false)
    equal(a:save('bad.mkv', {position=0/0}), false)
    equal(a:save('', {position=4}), false)
    equal(a:save('bad.mkv', {position=4, duration='invalid'}), false)
end)
test('completed temporary journal recovers after interrupted replacement', function()
    local path = utils.join_path(dir, 'history-9999999999-1-1.jsonl.tmp')
    local f = assert(io.open(path, 'wb'))
    f:write('{"version":1,"path":"recovered.mkv","position":12,"updated":9999999999}\n')
    f:close()
    local saved = module('history').new(dir, 20):get('recovered.mkv')
    assert(saved); equal(saved.position, 12)
end)
test('later saves win when the fractional monotonic clock wraps', function()
    local a = module('history').new(dir, 20)
    local get_time = mp.get_time
    mp.get_time = function() return 0.9 end
    a:save('wrap.mkv', {position=10,duration=100})
    mp.get_time = function() return 1.1 end
    a:save('wrap.mkv', {position=20,duration=100})
    mp.get_time = get_time
    equal(a:get('wrap.mkv').position, 20)
end)
