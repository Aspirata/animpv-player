test('explicit season and episode ignore release metadata', function()
    local e = module('rules').episode('[Group] Show S02E03 [1080p] [DEADBEEF].mkv')
    equal(e.season, 2); equal(e.number, 3); equal(e.series, 'show')
end)
test('bracket and dash episode formats', function()
    local r = module('rules')
    equal(r.episode('[Group] Название - 012 [1920x1080].mkv').number, 12)
    equal(r.episode('Название [03].ass').number, 3)
end)
test('resolution year checksum and specials are not episodes', function()
    local r = module('rules')
    for _, name in ipairs({'Movie 2024 1080p.mkv', 'Movie [1080p] [A012BC34].mkv',
        'Show OP 01.mkv', 'Show NCED 02.mkv', 'Show - 1080.mkv'}) do
        equal(r.episode(name), nil)
    end
end)
test('external tracks match series as well as episode', function()
    local r = module('rules')
    equal(r.match('Show S01E02.mkv', 'Other S01E02.ass'), nil)
    assert(r.match('Show S01E02.mkv', 'Show S01E02.ru.ass'))
    assert(r.match('Show - 02.mkv', '02.ass'))
    equal(r.match('Show S01E02.mkv', 'Show S02E02.ass'), nil)
end)
test('natural ordering handles leading zero and long numbers deterministically', function()
    local r = module('rules')
    local names = {'Show 10.mkv', 'Show 2.mkv', 'Show 01.mkv'}
    table.sort(names, r.natural_less)
    equal(table.concat(names, '|'), 'Show 01.mkv|Show 2.mkv|Show 10.mkv')
    equal(r.natural_less('2.mkv', '02.mkv') ~= r.natural_less('02.mkv', '2.mkv'), true)
end)
test('automatic episodes exclude audio specials other series and duplicate versions', function()
    local r = module('rules')
    local list, ambiguous = r.videos({'Show - 01.mkv', 'Show - 02.mkv',
        'Show - 02.mp4', 'Show - 03.mkv', 'Show OP 01.mkv', 'Other - 04.mkv',
        'Show - 04.mka', 'cover.jpg'}, 'Show - 01.mkv')
    equal(#list, 2); equal(list[1], 'Show - 01.mkv'); equal(list[2], 'Show - 03.mkv')
    equal(#ambiguous, 1); equal(#ambiguous[1], 2)
end)
test('unnumbered folder falls back to video-only natural order', function()
    local list = module('rules').videos({'movie.mkv', 'cover.jpg', 'audio.mka', 'film.mp4'}, 'movie.mkv')
    equal(table.concat(list, '|'), 'film.mp4|movie.mkv')
end)
test('mixed recognized filename formats sort by episode rather than release prefix', function()
    local list = module('rules').videos({'Show - 02.mkv', 'Show S01E01.mkv',
        '[A] Show S01E03.mkv'}, 'Show S01E01.mkv')
    equal(table.concat(list, '|'), 'Show S01E01.mkv|Show - 02.mkv|[A] Show S01E03.mkv')
end)
test('voice preference identity ignores transient track id and episode filename', function()
    local r = module('rules')
    equal(r.track_key({type='audio', lang='rus', title='Studio', id=2}),
        r.track_key({type='audio', lang='rus', title='Studio', id=8}))
    assert(r.track_key({type='audio', lang='rus', title='Studio'}) ~=
        r.track_key({type='audio', lang='rus', title='Other'}))
end)
test('ASS escaping strips control bytes and blocks brace/backslash instructions', function()
    local text = module('rules').escape('x{\\pos(0,0)}\n\001y')
    assert(not text:find('{', 1, true)); assert(not text:find('\\', 1, true))
    assert(not text:find('\001', 1, true)); assert(not text:find('\n', 1, true))
end)
