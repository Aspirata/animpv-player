local utils = require 'mp.utils'
local root = utils.join_path(mp.get_opt('animpv-test-root'), 'library')
test('discovery reads nested Cyrillic audio but keeps video navigation at root', function()
    local service = module('library').new({max_depth=3, max_files=20, max_dirs=10})
    local result = service:scan_sync(root)
    equal(#result.videos, 2); equal(#result.audio, 1); equal(#result.subtitles, 0)
    equal(result.incomplete, false)
    assert(result.audio[1]:find('Озвучка Studio', 1, true))
end)
test('discovery limits report partial results instead of silently omitting them', function()
    local result = module('library').new({max_depth=0, max_files=20, max_dirs=10}):scan_sync(root)
    equal(result.incomplete, true); assert(result.reason ~= '')
end)
test('discovery reuses cache until manual refresh', function()
    local s = module('library').new({max_depth=3, max_files=20, max_dirs=10, cache_seconds=60})
    local a = s:scan_sync(root)
    local path = utils.join_path(root, 'Show - 03.mkv')
    local f = assert(io.open(path, 'wb')); f:close()
    equal(#s:scan_sync(root).videos, #a.videos)
    s:refresh(); equal(#s:scan_sync(root).videos, 3)
    os.remove(path)
end)
test('cancel invalidates the previous scan generation', function()
    local s = module('library').new({max_depth=3, max_files=20, max_dirs=10})
    local called = false
    s:scan(root, function() called = true end)
    s:cancel()
    -- The callback is deferred; a canceled job must not be allowed to publish.
    s:step()
    equal(called, false)
end)
if utils.file_info(utils.join_path(root,'Loop')) then
    test('directory junction back to root is not traversed',function()
        local service=module('library').new({max_depth=3,max_files=20,max_dirs=10})
        local result=service:scan_sync(root)
        equal(result.incomplete,false); equal(#result.audio,1); equal(service.reads,2)
    end)
end
